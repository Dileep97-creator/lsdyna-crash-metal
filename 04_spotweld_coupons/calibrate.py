#!/usr/bin/env python3
"""
Fit the *MAT_SPOTWELD resultant failure envelope and write the card.

Input : data/weld_tests.csv  - one row per load angle, peak force at
        weld failure, from the test rig or from the swforc trace of the
        matching simulation.

Fit   : (|N_rr|/NRR)^NF + (|N_rs|/NRS)^NF = 1
        with N_rr = F sin(theta) (normal) and N_rs = F cos(theta) (shear)

Output: results/mat100_spotweld.k, results/weld_envelope.png,
        results/fit_report.txt

Why fit rather than take the datasheet number: a weld quoted only by its
lap-shear strength is a single point on a two-dimensional surface. Crash
loading is mixed-mode almost everywhere, and the exponent NF controls how
much strength survives that mixing. Choosing NF = 2 by default, as many
decks do, can be off by tens of percent in the mid-angle range.

    python3 calibrate.py
"""

from __future__ import annotations

import argparse
import csv
import math
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "tools"))
from kfile import Deck   # noqa: E402
import materials as mat  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "data", "weld_tests.csv")
OUT = os.path.join(HERE, "results")
MID_WELD = 3


def load(path):
    rows = []
    with open(path) as fh:
        body = [ln for ln in fh if not ln.lstrip().startswith("#")]
        for r in csv.DictReader(body):
            if not r.get("angle_deg"):
                continue
            rows.append((float(r["angle_deg"]), float(r["peak_force_kn"]),
                         r.get("source", "").strip()))
    if len(rows) < 3:
        raise SystemExit(f"need at least 3 load angles in {path}")
    return sorted(rows)


def residual(p, n, s):
    nrr, nrs, nf = p
    return (np.abs(n) / nrr) ** nf + (np.abs(s) / nrs) ** nf - 1.0


def fit(n, s):
    """Least squares on the envelope equation. Bounded so the exponent
    stays in the range where the surface is convex and physical."""
    guess = [max(np.max(n), 1e-3) * 1.05, max(np.max(s), 1e-3) * 1.05, 2.0]
    try:
        from scipy.optimize import least_squares
        r = least_squares(residual, guess, args=(n, s),
                          bounds=([1e-4, 1e-4, 1.0], [1e4, 1e4, 8.0]))
        return tuple(r.x), "scipy.least_squares"
    except Exception:
        best, bp = np.inf, guess
        for nf in np.linspace(1.0, 6.0, 51):
            for a in np.linspace(0.8, 2.0, 41):
                for b in np.linspace(0.8, 2.0, 41):
                    p = (guess[0] * a, guess[1] * b, nf)
                    r = float(np.sum(residual(p, n, s) ** 2))
                    if r < best:
                        best, bp = r, p
        return bp, "grid search"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", default=DATA)
    ap.add_argument("--nugget", type=float, default=5.0,
                    help="nugget diameter [mm], reported as nominal stress")
    args = ap.parse_args()
    os.makedirs(OUT, exist_ok=True)

    rows = load(args.csv)
    ang = np.array([r[0] for r in rows])
    F = np.array([r[1] for r in rows])
    th = np.radians(ang)
    n_res = F * np.sin(th)     # axial / normal resultant
    s_res = F * np.cos(th)     # shear resultant

    (nrr, nrs, nf), method = fit(n_res, s_res)

    pred_F = []
    for t in th:
        # solve for the force magnitude that lands on the fitted surface
        f = np.linspace(0.0, 5.0 * max(F), 20001)
        g = (np.abs(f * math.sin(t)) / nrr) ** nf + \
            (np.abs(f * math.cos(t)) / nrs) ** nf - 1.0
        pred_F.append(float(f[np.argmin(np.abs(g))]))
    pred_F = np.array(pred_F)
    err = (pred_F - F) / F * 100.0

    area = math.pi * (args.nugget / 2.0) ** 2

    d = Deck("MAT_SPOTWELD with fitted resultant failure envelope")
    d.note(
        f"generated by 04_spotweld_coupons/calibrate.py from {os.path.basename(args.csv)}\n"
        f"envelope (|Nrr|/{nrr:.4f})^{nf:.3f} + (|Nrs|/{nrs:.4f})^{nf:.3f} = 1   [kN]\n"
        f"fit method {method}, worst point error {np.max(np.abs(err)):.1f}%\n"
        f"nugget diameter {args.nugget:g} mm -> nominal normal strength "
        f"{nrr/area*1000:.0f} MPa")
    d.lines.append("*MAT_SPOTWELD_TITLE")
    d.lines.append("spot weld nugget, calibrated resultant failure")
    d.cards(
        (("mid", "ro", "e", "pr", "sigy", "et", "dt", "tfail"),
         (MID_WELD, mat.RHO_STEEL, mat.E_STEEL, mat.NU_STEEL, 0.80,
          0.0, 0.0, 0.0)),
        (("efail", "nrr", "nrs", "nrt", "mrr", "mss", "mtt", "nf"),
         (0.0, nrr, nrs, 0.0, 0.0, 0.0, 0.0, nf)))
    kpath = os.path.join(OUT, "mat100_spotweld.k")
    d.write(kpath)

    lines = [
        "Spot weld failure envelope calibration",
        "=" * 52,
        f"input            {os.path.relpath(args.csv, HERE)}",
        f"fit method       {method}",
        f"NRR (normal)     {nrr:.4f} kN",
        f"NRS (shear)      {nrs:.4f} kN",
        f"NF  (exponent)   {nf:.3f}",
        f"NRS/NRR ratio    {nrs/nrr:.3f}",
        "",
        f"{'angle':>7} {'test kN':>9} {'fit kN':>9} {'error %':>9}  source",
    ]
    for (a, f, src), pf, e in zip(rows, pred_F, err):
        lines.append(f"{a:7.1f} {f:9.3f} {pf:9.3f} {e:9.1f}  {src}")
    lines += [
        "",
        f"nominal nugget area {area:.2f} mm2",
        f"normal strength     {nrr/area*1000:.0f} MPa",
        f"shear strength      {nrs/area*1000:.0f} MPa",
        "",
        "If NF comes out near 2 the envelope is close to elliptical. Values",
        "well above 2 mean the weld keeps most of its strength under mixed",
        "loading; values below 2 mean mixed modes are more damaging than an",
        "elliptical assumption predicts.",
        "",
        f"card written to {os.path.relpath(kpath, HERE)}",
    ]
    report = "\n".join(lines)
    open(os.path.join(OUT, "fit_report.txt"), "w").write(report + "\n")
    print(report)

    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        fig, ax = plt.subplots(figsize=(5.6, 5.2))
        t = np.linspace(0, math.pi / 2, 400)
        env = []
        for tt in t:
            f = np.linspace(0.0, 5.0 * max(F), 20001)
            g = (np.abs(f * np.sin(tt)) / nrr) ** nf + \
                (np.abs(f * np.cos(tt)) / nrs) ** nf - 1.0
            env.append(f[np.argmin(np.abs(g))])
        env = np.array(env)
        ax.plot(env * np.cos(t), env * np.sin(t), "-", lw=2,
                label=f"fitted envelope, NF={nf:.2f}")
        ax.plot(s_res, n_res, "o", ms=8, label="coupon tests")
        for a, sx, ny_ in zip(ang, s_res, n_res):
            ax.annotate(f"{a:g}$^\\circ$", (sx, ny_),
                        textcoords="offset points", xytext=(7, 4), fontsize=9)
        ax.set_xlabel("shear resultant $N_{rs}$ [kN]")
        ax.set_ylabel("normal resultant $N_{rr}$ [kN]")
        ax.set_title("Spot weld failure envelope")
        ax.set_aspect("equal")
        ax.grid(alpha=0.3)
        ax.legend()
        fig.tight_layout()
        fig.savefig(os.path.join(OUT, "weld_envelope.png"), dpi=150)
        print(f"\nplot written to {os.path.relpath(OUT, HERE)}/weld_envelope.png")
    except ImportError:
        print("\nmatplotlib not installed - skipped plot")


if __name__ == "__main__":
    main()
